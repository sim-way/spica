import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(scriptDirectory, "..");
const repositoryRoot = path.resolve(packageRoot, "../..");
const source = path.join(repositoryRoot, "skills", "spica-architect", "SKILL.md");
const destination = path.join(packageRoot, "dist", "skills", "spica-architect", "SKILL.md");
const embeddedTsDestination = path.join(packageRoot, "src", "bundledSkill.ts");

const skillContent = fs.readFileSync(source, "utf-8");

fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, skillContent, "utf-8");
console.log("Copied spica-architect skill into packages/core/dist/skills/spica-architect/SKILL.md");

const generatedModule = `// Auto-generated by scripts/vendor-skill.mjs — do not edit manually.
export const BUNDLED_SKILL_CONTENT = ${JSON.stringify(skillContent)};
`;
fs.writeFileSync(embeddedTsDestination, generatedModule, "utf-8");
console.log("Generated embedded skill module in packages/core/src/bundledSkill.ts");
